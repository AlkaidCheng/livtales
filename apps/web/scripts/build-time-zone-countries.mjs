// Writes lib/time-zone-countries.ts from the tz database's zone.tab: the
// country each zone serves, so the time zone picker can find a zone by its
// country's name. Run it after a tzdata update:
//
//   TZDIR=/usr/share/zoneinfo node scripts/build-time-zone-countries.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = process.env.TZDIR ?? "/usr/share/zoneinfo";
const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "lib",
  "time-zone-countries.ts",
);

const zoneTab = readFileSync(join(root, "zone.tab"), "utf8");
const version =
  /^# version (\S+)/m.exec(
    readFileSync(join(root, "tzdata.zi"), "utf8"),
  )?.[1] ?? "unknown";

// zone.tab lists a country's most populous zone first.
const countries = new Map();
const leads = new Map();
for (const line of zoneTab.split("\n")) {
  if (line.startsWith("#") || line.trim() === "") continue;
  const [code, , zone] = line.split("\t");
  if (!code || !zone) continue;
  countries.set(zone, code);
  if (!leads.has(code)) leads.set(code, zone);
}

const record = (map) =>
  [...map]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `  "${key}": "${value}",`)
    .join("\n");

writeFileSync(
  out,
  `// Generated by scripts/build-time-zone-countries.mjs from tzdata ${version}; do not edit.

/** The country (ISO 3166 code) each zone in the tz database's zone.tab serves. */
export const zoneCountries: Readonly<Record<string, string>> = {
${record(countries)}
};

/** Each country's most populous zone, the one zone.tab lists first for it. */
export const countryLeadZones: ReadonlySet<string> = new Set([
${[...leads.values()]
  .sort()
  .map((zone) => `  "${zone}",`)
  .join("\n")}
]);
`,
);
console.log(`wrote ${countries.size} zones (tzdata ${version})`);
